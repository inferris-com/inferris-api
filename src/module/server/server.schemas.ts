import z from "zod";
import { BigIntStringSchema } from "../../shared/common.schemas.js";

// Types
export const serverTypeSchema = z.enum(["paper", "velocity", "unspecified"]);
export const serverEnvTypeSchema = z.enum(["production", "beta", "alpha", "development"]);
export const serverStatusTypeSchema = z.enum(["online", "offline"]);
export const serverAccessTypeSchema = z.enum(["open", "min_rank", "permission"]);
export const lockdownScopeTypeSchema = z.enum(["global", "local"]);

// Example: GET /servers/:serverId
export const serverIdParamsSchema = z.object({
  serverId: z.guid({ message: "Invalid server UUID format." }),
});

// POST
export const createServerBodySchema = z
  .object({
    // id is auto-generated by PG
    name: z.string().max(100).nonempty(),

    type: serverTypeSchema,
    environment: serverEnvTypeSchema,
    status: serverStatusTypeSchema.optional(),

    port: z.int().min(1).max(65535).nullable(),
    version: z.string(),
  })
  .strict();

// POST
export const createLockdownBodySchema = z
  .object({
    scope: lockdownScopeTypeSchema,
    requiredRankKey: z.string().max(30),
    reason: z.string(),
    issuedByActorId: z.guid(),
    isActive: z.boolean().optional().default(true),
    startsAtMs: BigIntStringSchema,
    endsAtMs: BigIntStringSchema.optional().nullable(),
  })
  .strict();

// PUT
export const replaceServerAccessBodySchema = z
  .object({
    mode: serverAccessTypeSchema,
    requiredPermissionId: z.uuid().nullable(),
    requiredRankKey: z.string().max(30).nullable(),
    note: z.string().nullable(),
  })
  .strict();

// PATCH
export const updateServerBodySchema = z
  .object({
    // id is auto-generated by PG
    name: z.string().max(100).nonempty().optional(),

    type: serverTypeSchema.optional(),
    environment: serverEnvTypeSchema.optional(),
    status: serverStatusTypeSchema.optional(),

    port: z.int().min(1).max(65535).optional().nullable(),
    version: z.string(),

    lastStartedAtMs: BigIntStringSchema.optional(),
    lastHeartbeatAtMs: BigIntStringSchema.optional(),

    createdAtMs: BigIntStringSchema.optional(),
    lastUpdatedAtMs: BigIntStringSchema.optional().nullable(),
  })
  .strict()
  .refine((body) => Object.keys(body).length > 0, {
    message: "At least one field must be provided.",
  });

// PATCH
export const updateLockdownBodySchema = z
  .object({
    scope: lockdownScopeTypeSchema.optional(),
    requiredRankKey: z.string().max(30).optional(),
    reason: z.string().optional(),
    issuedByActorId: z.guid().optional(),
    isActive: z.boolean().optional(),
    startsAtMs: BigIntStringSchema.optional(),
    endsAtMs: BigIntStringSchema.optional().nullable(),
  })
  .strict()
  .refine((body) => Object.keys(body).length > 0, {
    message: "At least one field must be provided.",
  });

export type ServerType = z.infer<typeof serverTypeSchema>;
export type ServerAccessType = z.infer<typeof serverAccessTypeSchema>;
export type LockdownScopeType = z.infer<typeof lockdownScopeTypeSchema>;

export type ServerIdParamsSchema = z.infer<typeof serverIdParamsSchema>;

export type CreateServerBody = z.infer<typeof createServerBodySchema>;
export type CreateLockdownBody = z.infer<typeof createLockdownBodySchema>;
export type CreateLockdownInput = ServerIdParamsSchema & CreateLockdownBody;
export type UpdateServerBody = z.infer<typeof updateServerBodySchema>;
export type ReplaceServerAccessBody = z.infer<typeof replaceServerAccessBodySchema>;
export type UpdateLockdownBody = z.infer<typeof updateLockdownBodySchema>;
